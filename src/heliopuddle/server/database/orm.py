# BIGINT on Postgres, INTEGER on SQLite (so SQLite autoincrement works).
BigId = BigInteger().with_variant(Integer(), "sqlite")


def utcnow() -> datetime:
    """Current time, timezone-aware UTC."""
    return datetime.now(UTC)


class UTCDateTime(TypeDecorator[datetime]):
    """A timezone-aware UTC datetime on every backend.

    SQLite has no timezone support and returns naive values; this type stores
    UTC and always returns aware UTC datetimes. Naive inputs are taken as UTC.
    """

    impl = DateTime(timezone=True)
    cache_ok = True

    def process_bind_param(self, value: datetime | None, dialect: Dialect) -> datetime | None:
        if value is not None and value.tzinfo is not None:
            value = value.astimezone(UTC)
            if dialect.name == "sqlite":
                value = value.replace(tzinfo=None)
        return value

    def process_result_value(self, value: datetime | None, dialect: Dialect) -> datetime | None:
        if value is not None:
            value = value.replace(tzinfo=UTC) if value.tzinfo is None else value.astimezone(UTC)
        return value


class Base(DeclarativeBase):
    """Declarative base for all heliopuddle tables."""


class Project(Base):
    __tablename__ = "project"

    id: Mapped[int] = mapped_column(BigId, primary_key=True)
    name: Mapped[str] = mapped_column(String(255), unique=True)

    storage_locations: Mapped[list[StorageLocation]] = relationship(
        back_populates="project", order_by="StorageLocation.id"
    )


class StorageLocation(Base):
    __tablename__ = "storage_location"
    __table_args__ = (UniqueConstraint("project_id", "name"),)

    id: Mapped[int] = mapped_column(BigId, primary_key=True)
    project_id: Mapped[int] = mapped_column(ForeignKey("project.id"))
    name: Mapped[str] = mapped_column(String(255))
    url: Mapped[str] = mapped_column(String(2048))
    accept_external_changes: Mapped[bool] = mapped_column(Boolean, default=True)
    active: Mapped[bool] = mapped_column(Boolean, default=True)

    project: Mapped[Project] = relationship(back_populates="storage_locations")


class Series(Base):
    __tablename__ = "series"
    __table_args__ = (UniqueConstraint("project_id", "series_key"),)

    id: Mapped[int] = mapped_column(BigId, primary_key=True)
    project_id: Mapped[int] = mapped_column(ForeignKey("project.id"))
    series_key: Mapped[str] = mapped_column(String(2048))
    # ``number`` or ``text``: the kind of every version in the series, set by its
    # first versioned file (migration 0008); NULL while it has none.
    version_type: Mapped[str | None] = mapped_column(String(8), nullable=True)
    latest_file_id: Mapped[int | None] = mapped_column(
        ForeignKey("file.id", use_alter=True, name="fk_series_latest_file"), nullable=True
    )


# Byte-wise comparison of text versions: ``COLLATE "C"`` on Postgres (SQLite
# compares bytes already and has no "C" collation).
VersionText = String(255).with_variant(String(255, collation="C"), "postgresql")


class File(Base):
    __tablename__ = "file"
    __table_args__ = (
        CheckConstraint(
            "version_number IS NULL OR version_text IS NULL", name="ck_file_one_version"
        ),
    )

    id: Mapped[int] = mapped_column(BigId, primary_key=True)
    project_id: Mapped[int] = mapped_column(ForeignKey("project.id"))
    path: Mapped[str] = mapped_column(String(2048))
    name: Mapped[str] = mapped_column(String(1024))
    # Generated by the database for search (migration 0007; virtual on SQLite).
    path_lower: Mapped[str] = mapped_column(String(2048), Computed("lower(path)", persisted=True))
    name_lower: Mapped[str] = mapped_column(String(1024), Computed("lower(name)", persisted=True))
    series_id: Mapped[int] = mapped_column(ForeignKey("series.id"), index=True)
    # At most one is set (``ck_file_one_version``; migration 0008).
    version_number: Mapped[int | None] = mapped_column(BigInteger, nullable=True)
    version_text: Mapped[str | None] = mapped_column(VersionText, nullable=True)
    content_date: Mapped[datetime | None] = mapped_column(UTCDateTime, nullable=True)
    size: Mapped[int] = mapped_column(BigInteger)
    hash: Mapped[str] = mapped_column(String(128))
    hash_algo: Mapped[str] = mapped_column(String(32), default="md5")
    file_metadata: Mapped[dict[str, Any] | None] = mapped_column("metadata", JSON, nullable=True)
    is_latest: Mapped[bool] = mapped_column(Boolean, default=True)
    ignored_from_all_rules: Mapped[bool] = mapped_column(
        Boolean, default=False, server_default=false()
    )
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow, onupdate=utcnow)
    deleted_at: Mapped[datetime | None] = mapped_column(UTCDateTime, nullable=True)
    created_by: Mapped[str | None] = mapped_column(String(255), nullable=True)
    updated_by: Mapped[str | None] = mapped_column(String(255), nullable=True)

    project: Mapped[Project] = relationship()
    series: Mapped[Series] = relationship(foreign_keys=[series_id])
    copies: Mapped[list[FileStorageLocation]] = relationship(
        back_populates="file", order_by="FileStorageLocation.storage_location_id"
    )


# Paths are unique among non-deleted files of a project.
Index(
    "uq_file_project_path_live",
    File.project_id,
    File.path,
    unique=True,
    sqlite_where=File.deleted_at.is_(None),
    postgresql_where=File.deleted_at.is_(None),
)
Index("ix_file_updated_at_id", File.updated_at, File.id)
# Latest and version-history lookups within a series (migration 0008).
Index("ix_file_series_version_number", File.series_id, File.version_number.desc())
Index("ix_file_series_version_text", File.series_id, File.version_text.desc())


class FileStorageLocation(Base):
    __tablename__ = "file_storage_location"
    __table_args__ = (UniqueConstraint("file_id", "storage_location_id"),)

    id: Mapped[int] = mapped_column(BigId, primary_key=True)
    file_id: Mapped[int] = mapped_column(ForeignKey("file.id"))
    storage_location_id: Mapped[int] = mapped_column(ForeignKey("storage_location.id"))
    state: Mapped[FileState] = mapped_column(
        Enum(
            FileState,
            name="file_state",
            native_enum=False,
            length=16,
            values_callable=lambda e: [m.value for m in e],
        )
    )
    size: Mapped[int | None] = mapped_column(BigInteger, nullable=True)
    mtime: Mapped[datetime | None] = mapped_column(UTCDateTime, nullable=True)
    hash: Mapped[str | None] = mapped_column(String(128), nullable=True)
    last_seen_at: Mapped[datetime | None] = mapped_column(UTCDateTime, nullable=True)
    # When the file arrived in this storage location: first recorded here, or
    # last copied or moved here by a rule (SVC-29, migration 0009).
    arrived_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow, onupdate=utcnow)
    # Operation ownership (docs/design/operations.md, migration 0004).
    generation: Mapped[int] = mapped_column(BigInteger, default=0, server_default="0")
    op_token: Mapped[str | None] = mapped_column(String(36), nullable=True, unique=True)
    op_deadline: Mapped[datetime | None] = mapped_column(UTCDateTime, nullable=True)
    pending_hash: Mapped[str | None] = mapped_column(String(128), nullable=True)
    pending_size: Mapped[int | None] = mapped_column(BigInteger, nullable=True)
    # What an overwrite will set on the file when (and only if) it publishes.
    pending_metadata: Mapped[dict[str, Any] | None] = mapped_column(JSON, nullable=True)
    pending_content_date: Mapped[datetime | None] = mapped_column(UTCDateTime, nullable=True)
    pending_by: Mapped[str | None] = mapped_column(String(255), nullable=True)
    # True when the upload writes a unique staging path and publishes it, because an
    # object already existed at the final path when it was reserved.
    pending_staged: Mapped[bool] = mapped_column(Boolean, default=False, server_default=false())
    # Token of the upload whose content a repair published; lets that upload's
    # late complete answer 200. Cleared by the next content-changing transition.
    published_token: Mapped[str | None] = mapped_column(String(36), nullable=True)
    # A move's source delete: the verified destination copy that must still hold the
    # content before an interrupted delete is retried (migration 0005).
    move_destination_id: Mapped[int | None] = mapped_column(BigInteger, nullable=True)

    file: Mapped[File] = relationship(back_populates="copies")
    storage_location: Mapped[StorageLocation] = relationship()


