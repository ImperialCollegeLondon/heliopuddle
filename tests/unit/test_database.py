    url = f"sqlite:///{tmp_path / 'hp.db'}"
    upgrade_to_head(url)
    assert schema_diffs(url) == []
    engine = create_engine_for(url)
    insp = inspect(engine)
    columns = {c["name"]: c for c in insp.get_columns("index_progress")}
    assert set(columns) >= {"storage_location_id", "last_full_at", "last_incremental_at"}
    assert insp.get_pk_constraint("index_progress")["constrained_columns"] == [
        "storage_location_id"
    ]
    assert columns["last_full_at"]["nullable"] and columns["last_incremental_at"]["nullable"]
    (fk,) = insp.get_foreign_keys("index_progress")
    assert fk["referred_table"] == "storage_location"
    engine.dispose()


