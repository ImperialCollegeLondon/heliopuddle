@pytest.mark.req("DB-01")
def test_upgrade_creates_schema_matching_models(tmp_path: Path) -> None:
    url = f"sqlite:///{tmp_path / 'nested' / 'dir' / 'hp.db'}"
    assert not is_at_head(url)
    assert current_revision(url) is None

    upgrade_to_head(url)

    assert (tmp_path / "nested" / "dir" / "hp.db").exists()
    assert is_at_head(url)
    assert current_revision(url) == head_revision()
    assert schema_diffs(url) == []

    engine = create_engine_for(url)
    insp = inspect(engine)
    assert set(insp.get_table_names()) >= {
        "project",
        "storage_location",
        "series",
        "file",
        "file_storage_location",
    }
    assert "active" in {c["name"] for c in insp.get_columns("storage_location")}
    (live_index,) = [
        i for i in insp.get_indexes("file") if i["name"] == "uq_file_project_path_live"
    ]
    assert live_index["unique"]
    assert live_index["column_names"] == ["project_id", "path"]
    uniques = insp.get_unique_constraints("file_storage_location")
    assert ["file_id", "storage_location_id"] in [u["column_names"] for u in uniques]
    fks = insp.get_foreign_keys("series")
    assert {"file", "project"} == {fk["referred_table"] for fk in fks}
    engine.dispose()

    # Running again is a no-op.
    upgrade_to_head(url)
    assert is_at_head(url)


