@pytest.mark.req("DB-01")
@pytest.mark.req("DB-02")
def test_sqlite_wal_foreign_keys_deferred_reads_and_immediate_writes(tmp_path: Path) -> None:
    db = tmp_path / "hp.db"
    url = f"sqlite:///{db}"
    upgrade_to_head(url)
    engine = create_engine_for(url)
    statements: list[str] = []
    event.listen(
        engine, "before_cursor_execute", lambda _c, _cur, stmt, *_: statements.append(stmt)
    )

    with engine.connect() as conn:
        assert conn.exec_driver_sql("PRAGMA journal_mode").scalar() == "wal"
        assert conn.exec_driver_sql("PRAGMA foreign_keys").scalar() == 1

    Session = make_sessionmaker(engine)
    # The same SQLite library as the engine: two copies of SQLite in one process
    # do not see each other's file locks.
    dbapi = sqlite_module()
    other = dbapi.connect(db, timeout=0, isolation_level=None)
    with Session.begin() as session:
        # A read transaction is deferred: it does not hold the write lock.
        session.execute(text("SELECT 1"))
        other.execute("BEGIN IMMEDIATE")
        other.execute("ROLLBACK")
    assert "BEGIN" in statements and "BEGIN IMMEDIATE" not in statements

    with write_session(Session) as session:
        # A write transaction holds the write lock from its first statement.
        session.execute(text("SELECT 1"))
        with pytest.raises(dbapi.OperationalError, match="locked"):
            other.execute("BEGIN IMMEDIATE")
        session.add(Project(name="p"))
    other.close()
    assert "BEGIN IMMEDIATE" in statements
    with Session() as session:
        assert session.scalar(select(Project.name)) == "p"

    # A write session rolls back on error.
    with pytest.raises(RuntimeError), write_session(Session) as session:
        session.add(Project(name="q"))
        session.flush()
        raise RuntimeError("boom")
    with Session() as session:
        assert session.scalars(select(Project.name)).all() == ["p"]

    # Foreign keys are enforced.
    with pytest.raises(Exception, match="FOREIGN KEY"), write_session(Session) as session:
        session.add(Series(project_id=999, series_key="x"))
    engine.dispose()


@pytest.mark.req("DB-01")
def test_datetimes_round_trip_as_utc(tmp_path: Path) -> None:
    url = f"sqlite:///{tmp_path / 'hp.db'}"
    upgrade_to_head(url)
    engine = create_engine_for(url)
    Session = make_sessionmaker(engine)
    plus_two = timezone(timedelta(hours=2))
    with Session.begin() as session:
        project = Project(name="p")
        series = Series(series_key="a")
        session.add(project)
        session.flush()
        series.project_id = project.id
        session.add(series)
        session.flush()
        f = File(
            project_id=project.id,
            path="a",
            name="a",
            series_id=series.id,
            size=1,
            hash="h",
            content_date=datetime(2024, 1, 1, 12, tzinfo=plus_two),
            deleted_at=datetime(2024, 1, 2, 3),  # naive is taken as UTC
        )
        session.add(f)
        session.flush()
        file_id = f.id
    with Session() as session:
        f = session.get_one(File, file_id)
        assert f.content_date == datetime(2024, 1, 1, 10, tzinfo=UTC)
        assert f.content_date is not None and f.content_date.tzinfo is UTC
        assert f.deleted_at == datetime(2024, 1, 2, 3, tzinfo=UTC)
        assert f.created_at.tzinfo is UTC
    engine.dispose()


def test_memory_sqlite_and_non_sqlite_urls() -> None:
    engine = create_engine_for("sqlite://")
    with engine.connect() as conn:
        assert conn.execute(text("SELECT 1")).scalar() == 1
    engine.dispose()
    assert is_sqlite("sqlite:///x.db")
    assert not is_sqlite("postgresql+psycopg://u@h/db")


@pytest.mark.req("DB-01")
def test_sqlite_engine_prefers_the_bundled_current_sqlite(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    import importlib
    import importlib.util

    from heliopuddle.server.database import engine as engine_module

    bundled = importlib.util.find_spec("pysqlite3") is not None
    eng = engine_module.create_engine_for(f"sqlite:///{tmp_path / 'a.db'}")
    try:
        assert eng.dialect.dbapi.__name__ == (  # type: ignore[union-attr]
            "pysqlite3.dbapi2" if bundled else "sqlite3"
        )
        with eng.connect() as conn:
            assert conn.exec_driver_sql("select sqlite_version()").scalar() == (
                eng.dialect.dbapi.sqlite_version  # type: ignore[union-attr]
            )
    finally:
        eng.dispose()

    real_import = importlib.import_module

    def no_pysqlite3(name: str, *args: object) -> object:
        if name.startswith("pysqlite3"):
            raise ImportError(name)
        return real_import(name, *args)  # type: ignore[arg-type]

    monkeypatch.setattr(engine_module.importlib, "import_module", no_pysqlite3)
    assert engine_module.sqlite_module() is sqlite3
